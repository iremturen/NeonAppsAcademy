import 'package:flutter/material.dart';

class CustomContainerModel {
  final double? width;
  final double? height;
  final Color? color;
  final EdgeInsetsGeometry? padding;
  final EdgeInsetsGeometry? margin;
  final BorderRadius? borderRadius;

  const CustomContainerModel({
    this.width,
    this.height,
    this.color,
    this.padding,
    this.margin,
    this.borderRadius,
  });
}

